#!/usr/bin/env bash
# Distribute agent instruction files from their sources to every runtime.
#
# Global instructions:
#   ~/.agent-tooling/.agents/AGENTS.md          (this repo, always)
#   <overlay>/.agents/AGENTS.md                 (appended, per overlay that has one)
#   -> ~/.claude/CLAUDE.md, ~/.codex/AGENTS.md, ~/.omp/agent/AGENTS.md, ~/.gemini/GEMINI.md
#      (only runtimes whose directory already exists)
#
# Project instructions (overlays only):
#   <overlay>/projects/<name>/AGENTS.md + <overlay>/projects/<name>/TARGET (one line: repo path)
#   -> <repo>/AGENTS.md, plus <repo>/CLAUDE.md containing "@AGENTS.md" when it is missing.
#
# Overlays default to ~/.agent-tooling-work; override with AGENT_TOOLING_OVERLAYS (colon-separated).
#
# Every generated file starts with a header that records the sha256 of its body.
# A target whose body no longer matches its header was edited in place (for example
# by an agent's memory feature); it is skipped unless --force, so move those edits
# into the source first. A target without a header is backed up to <file>.bak once.
#
# Usage: sync-agent-instructions.sh [--check] [--force]
#   --check  report what would change and exit 1 if anything is out of date; write nothing
#   --force  overwrite targets that were edited in place

set -euo pipefail

mode=apply
force=0
for arg in "$@"; do
	case "$arg" in
	--check) mode=check ;;
	--force) force=1 ;;
	*)
		echo "unknown argument: $arg" >&2
		exit 2
		;;
	esac
done

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
overlays="${AGENT_TOOLING_OVERLAYS:-$HOME/.agent-tooling-work}"

stale=0
skipped=0

sha() { sha256sum | cut -d' ' -f1; }

# Strip CR so Windows checkouts hash the same as everywhere else.
read_source() { tr -d '\r' <"$1"; }

expand_path() {
	local p
	p="$(tr -d '\r' <"$1" | head -n1 | sed 's/[[:space:]]*$//')"
	case "$p" in
	"~"/*) p="$HOME/${p#\~/}" ;;
	esac
	printf '%s' "$p"
}

# write_target <target> <body> <description of sources>
write_target() {
	local target="$1" body="$2" sources="$3"
	local hash header current current_body recorded
	hash="$(printf '%s\n' "$body" | sha)"
	header="<!-- Generated by ~/.agent-tooling (just instructions) from ${sources}. Edit the sources, not this file. sha256:${hash} -->"

	if [[ -f "$target" ]]; then
		current="$(tr -d '\r' <"$target")"
		if [[ "$current" == "$header"$'\n'"$body" ]]; then
			echo "ok        $target"
			return
		fi
		recorded="$(head -n1 <<<"$current" | sed -n 's/.*sha256:\([0-9a-f]*\) -->$/\1/p')"
		current_body="$(tail -n +2 <<<"$current")"
		if [[ -n "$recorded" && "$(printf '%s\n' "$current_body" | sha)" != "$recorded" && "$force" -eq 0 ]]; then
			echo "EDITED    $target (changed in place; move the edits into ${sources}, or rerun with --force)"
			skipped=$((skipped + 1))
			stale=$((stale + 1))
			return
		fi
	fi

	stale=$((stale + 1))
	if [[ "$mode" == check ]]; then
		echo "outdated  $target"
		return
	fi
	if [[ -f "$target" ]] && ! head -n1 "$target" | grep -q '^<!-- Generated by ~/.agent-tooling'; then
		cp "$target" "$target.bak"
		echo "backup    $target.bak"
	fi
	printf '%s\n%s\n' "$header" "$body" >"$target"
	echo "wrote     $target"
}

# ---- global instructions ----------------------------------------------------
global_src="$repo_root/.agents/AGENTS.md"
global_body="$(read_source "$global_src")"
global_sources="~/.agent-tooling/.agents/AGENTS.md"

IFS=':' read -r -a overlay_list <<<"$overlays"
for overlay in "${overlay_list[@]}"; do
	[[ -f "$overlay/.agents/AGENTS.md" ]] || continue
	global_body+=$'\n\n'"$(read_source "$overlay/.agents/AGENTS.md")"
	global_sources+=" + ${overlay/#"$HOME"/\~}/.agents/AGENTS.md"
done

declare -a global_targets=(
	"$HOME/.claude/CLAUDE.md"
	"$HOME/.codex/AGENTS.md"
	"$HOME/.omp/agent/AGENTS.md"
	"$HOME/.gemini/GEMINI.md"
)
for target in "${global_targets[@]}"; do
	[[ -d "$(dirname "$target")" ]] || continue
	write_target "$target" "$global_body" "$global_sources"
done

# ---- project instructions ---------------------------------------------------
for overlay in "${overlay_list[@]}"; do
	[[ -d "$overlay/projects" ]] || continue
	for project in "$overlay"/projects/*/; do
		project="${project%/}"
		[[ -f "$project/AGENTS.md" && -f "$project/TARGET" ]] || continue
		repo="$(expand_path "$project/TARGET")"
		if [[ ! -d "$repo" ]]; then
			echo "missing   $repo (from $project/TARGET)"
			continue
		fi
		write_target "$repo/AGENTS.md" "$(read_source "$project/AGENTS.md")" \
			"${project/#"$HOME"/\~}/AGENTS.md"
		if [[ ! -f "$repo/CLAUDE.md" ]]; then
			stale=$((stale + 1))
			if [[ "$mode" == apply ]]; then
				printf '@AGENTS.md\n' >"$repo/CLAUDE.md"
				echo "wrote     $repo/CLAUDE.md"
			else
				echo "outdated  $repo/CLAUDE.md"
			fi
		fi
	done
done

if [[ "$mode" == check ]]; then
	[[ "$stale" -eq 0 ]] || exit 1
elif [[ "$skipped" -gt 0 ]]; then
	exit 1
fi
